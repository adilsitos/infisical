type ImpactKind = "direct" | "indirect_di" | "indirect_graph";

interface RouteImpact {
  route: string;
  method: string;
  url: string;
  file: string;
  feature: string;
  operation_id: string;
  kind: ImpactKind;
  status?: "changed" | "added" | "removed";
  risk: Risk;
  reasons: string[];
  hash_before?: string;
  hash_after?: string;
  details?: ChangeDetail[];
  service_key?: string;
  service_methods?: string[];
  precision?: "method" | "module";
  depth?: number;
  chain?: string[];
  evidence?: string[];
}

interface WideImpact {
  reason: string;
  route_count: number;
  route_file_count: number;
  subsystems: { community: string; routes: number }[];
}

interface FileImpact {
  file: string;
  community: Community | null;
  service_keys: string[];
  direct: RouteImpact[];
  indirect: RouteImpact[];
  wide?: WideImpact;
  focus?: ChangeFocus;
  // Routes on the same service key that call a method this change did not touch. Reported as a
  // count, because the point of narrowing is not to print them.
  module_only_routes?: number;
  narrowing_notes?: string[];
}

interface ManifestView {
  routesByFile: Map<string, { route: string; signature: BehavioralSignature }[]>;
  routesByServiceKey: Map<string, { route: string; signature: BehavioralSignature }[]>;
  routeFiles: Set<string>;
}

const buildManifestView = (manifest: Manifest): ManifestView => {
  const routesByFile = new Map<string, { route: string; signature: BehavioralSignature }[]>();
  const routesByServiceKey = new Map<string, { route: string; signature: BehavioralSignature }[]>();

  for (const [route, signature] of Object.entries(manifest.routes ?? {})) {
    const entry = { route, signature };

    const byFile = routesByFile.get(signature.file);
    if (byFile) byFile.push(entry);
    else routesByFile.set(signature.file, [entry]);

    for (const key of new Set(signature.service_calls.map((call) => call.split(".")[0]))) {
      const byKey = routesByServiceKey.get(key);
      if (byKey) byKey.push(entry);
      else routesByServiceKey.set(key, [entry]);
    }
  }

  return { routesByFile, routesByServiceKey, routeFiles: new Set(routesByFile.keys()) };
};

const subsystemBreakdown = (
  routes: { file: string; feature: string }[],
  graph: GraphIndex | null
): { community: string; routes: number }[] => {
  const counts = new Map<string, number>();
  for (const route of routes) {
    const community = graph?.communityOfFile(route.file);
    const name = community?.name || route.feature;
    counts.set(name, (counts.get(name) ?? 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 6)
    .map(([community, routes]) => ({ community, routes }));
};

const toImpact = (
  entry: { route: string; signature: BehavioralSignature },
  kind: ImpactKind,
  scored: Scored,
  extra: Partial<RouteImpact> = {}
): RouteImpact => ({
  route: entry.route,
  method: entry.signature.method,
  url: entry.signature.url,
  file: entry.signature.file,
  feature: entry.signature.feature,
  operation_id: entry.signature.operation_id,
  kind,
  risk: scored.risk,
  reasons: scored.reasons,
  ...extra
});

