const matchesGlob = (candidate: string, pattern: string): boolean => {
  if (pattern.endsWith("/**")) return candidate.startsWith(pattern.slice(0, -2));
  if (pattern.startsWith("*")) return candidate.endsWith(pattern.slice(1));
  if (pattern.endsWith("*")) return candidate.startsWith(pattern.slice(0, -1));
  return candidate === pattern;
};

const loadRegistry = (registryPath: string): ProjectRegistry | null => {
  if (!existsSync(registryPath)) return null;
  const parsed = JSON.parse(readFileSync(registryPath, "utf-8")) as Partial<ProjectRegistry>;

  // The scaffold writes owner/team/slack as "" for a human to fill in. Left empty they are absent,
  // not present-and-blank, or every unfilled field renders as an empty table cell.
  const projects: Record<string, ProjectDef> = {};
  for (const [id, definition] of Object.entries(parsed.projects ?? {})) {
    const cleaned = { ...definition };
    for (const key of ["owner", "team", "slack", "jira", "status", "launch_date"] as const) {
      if (!cleaned[key]) delete cleaned[key];
    }
    projects[id] = cleaned;
  }

  return { analysis: parsed.analysis ?? {}, projects };
};

