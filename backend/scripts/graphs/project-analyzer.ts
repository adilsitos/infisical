interface ProjectOutput {
  project_id: string;
  project_name: string;
  source: ResolvedProject["source"];
  matched_by?: string;
  owner?: string;
  team?: string;
  slack?: string;
  jira?: string;
  status?: string;
  launch_date?: string;
  max_risk: Risk;
  headline: string;
  changed_files: string[];
  changed_code: ChangeFocus[];
  module_only_routes: number;
  narrowing_notes: string[];
  impacted_routes: {
    direct: RouteImpact[];
    indirect_di: RouteImpact[];
    indirect_graph: RouteImpact[];
  };
  changes: RouteImpact[];
  narratives: { route: string; kind: ImpactKind; narrative: string }[];
  wide_impact: (WideImpact & { file: string })[];
  action_items: ActionItem[];
}

interface Analysis {
  meta: Record<string, unknown>;
  summary: Record<string, unknown>;
  affected_projects: ProjectOutput[];
  wide_impact_files: (WideImpact & { file: string; project: string })[];
  no_route_impact: { file: string; project: string; reason: string }[];
  unowned_changes: { file: string; reason: string }[];
  skipped_files: { file: string; reason: string }[];
  unaffected_projects?: { project_id: string; project_name: string }[];
}

const METHOD_LIST_LIMIT = 6;

const capped = (items: string[], limit: number): string =>
  `${items.slice(0, limit).join(", ")}${items.length > limit ? `, and ${items.length - limit} more` : ""}`;

const methodSummary = (focus: ChangeFocus, withFile = true): string => {
  const prefix = withFile ? `${focus.file.split("/").pop() ?? focus.file}: ` : "";
  const labels = focus.categories.map((category) => category.label);
  const notes = focus.notes.length ? ` (${focus.notes.join("; ")})` : "";
  // A refusal is only informative for the file a service key is bound to. On a dal or fns file
  // there is no factory to resolve against and saying so on every one of them is noise.
  const refusal = !focus.narrowed && focus.di_bound && focus.reason ? ` (not narrowed: ${focus.reason})` : "";

  if (!focus.methods.length) {
    return `${prefix}${labels.join("; ") || focus.reason || "no method resolved"}${notes}`;
  }

  const methods = focus.methods.map((method) => {
    const via = method.via.length ? ` (via ${capped(method.via, 3)})` : "";
    const own = method.categories.map((category) => category.label);
    return `${method.name}${via}${own.length ? ` [${own.join("; ")}]` : ""}`;
  });

  return `${prefix}${capped(methods, METHOD_LIST_LIMIT)}${notes}${refusal}`;
};

const buildHeadline = (project: ProjectOutput): string => {
  const parts: string[] = [];
  const direct = project.impacted_routes.direct;
  if (direct.length) {
    const counts = { changed: 0, added: 0, removed: 0 };
    for (const route of direct) counts[route.status ?? "changed"] += 1;
    const segments = [
      counts.changed ? `${counts.changed} changed` : "",
      counts.added ? `${counts.added} new` : "",
      counts.removed ? `${counts.removed} removed` : ""
    ].filter(Boolean);
    parts.push(`${segments.join(", ")} route${direct.length === 1 ? "" : "s"}`);
  }

  const executes = project.impacted_routes.indirect_di.filter((route) => route.precision === "method").length;
  const reached =
    project.impacted_routes.indirect_di.filter((route) => route.precision !== "method").length +
    project.impacted_routes.indirect_graph.length;

  if (executes) parts.push(`${executes} route${executes === 1 ? " executes" : "s execute"} the changed code`);
  if (reached) parts.push(`${reached} route${reached === 1 ? "" : "s"} reached indirectly with no signature change`);
  if (project.module_only_routes) {
    parts.push(`${project.module_only_routes} on the same service key call methods this change does not touch`);
  }
  if (project.wide_impact.length) {
    parts.push(`${project.wide_impact.length} foundational file${project.wide_impact.length === 1 ? "" : "s"} with repo-wide reach`);
  }

  return parts.length ? `${parts.join("; ")}.` : "No route-level impact detected.";
};

const analyze = (
  report: DiffReport,
  manifest: Manifest,
  config: BehaviorConfig,
  graph: GraphIndex | null,
  di: DiBridge,
  registry: ProjectRegistry | null,
  options: Options
): Analysis => {
  const view = buildManifestView(manifest);
  const now = new Date();

  const directByFile = new Map<string, RouteImpact[]>();
  const push = (file: string, impact: RouteImpact) => {
    const bucket = directByFile.get(file);
    if (bucket) bucket.push(impact);
    else directByFile.set(file, [impact]);
  };

  for (const item of report.changed) {
    const scored = scoreDirectChange("changed", item.details, item.after);
    push(
      item.after.file,
      toImpact({ route: item.route, signature: item.after }, "direct", scored, {
        status: "changed",
        hash_before: item.before.hash,
        hash_after: item.after.hash,
        details: item.details
      })
    );
  }
  for (const item of report.added) {
    const scored = scoreDirectChange("added", [], item.signature);
    push(item.signature.file, toImpact(item, "direct", scored, { status: "added", hash_after: item.signature.hash }));
  }
  for (const item of report.removed) {
    const scored = scoreDirectChange("removed", [], item.signature);
    push(item.signature.file, toImpact(item, "direct", scored, { status: "removed", hash_before: item.signature.hash }));
  }

  // A changed route file that the gate found nothing in still needs analysing (its imports may
  // have moved), so the union is changed_files plus any file carrying a direct change - the latter
  // covers a report produced without meta, e.g. by an older run.
  const changedFiles = [...new Set([...(report.meta?.changed_files ?? []), ...directByFile.keys()])].sort();

  const skipped: Analysis["skipped_files"] = [];
  const analysable: string[] = [];
  for (const file of changedFiles) {
    if (isExcludedPath(file, config)) {
      skipped.push({ file, reason: "matches excluded_path_globs in .behavior-config.json" });
      continue;
    }
    analysable.push(file);
  }

  const focuses = buildFocuses(report, analysable);
  const narrowing = buildKeyNarrowing(analysable, di, focuses);

  const byProject = new Map<string, ProjectOutput>();
  const seenByProject = new Map<string, Set<string>>();
  const definitions = new Map<string, ProjectDef | undefined>();
  const unowned: Analysis["unowned_changes"] = [];
  const noRouteImpact: Analysis["no_route_impact"] = [];
  const wideFiles: Analysis["wide_impact_files"] = [];

  for (const file of analysable) {
    const impact = analyzeFile(file, view, di, graph, directByFile, focuses.get(file), narrowing, options);
    const project = resolveProject(impact, registry);

    // A file with no reachable route is reported, but not as an affected project - otherwise a
    // project appears in the rollup whose entire headline is "no impact detected", which is worse
    // than not listing it.
    if (!impact.direct.length && !impact.indirect.length && !impact.wide) {
      // Narrowing turns this into a real finding rather than a shrug: the change is wired to the
      // API, and no route on it calls what changed. Whatever exercises this code is not HTTP.
      const changedMethods = capped((impact.focus?.methods ?? []).map((method) => method.name), 4);
      const reason = impact.module_only_routes
        ? `wired to server.services.${impact.service_keys.join(", ")}, but no route calls the changed method(s) ` +
          `${changedMethods || "(none resolved)"} - ${impact.module_only_routes} route(s) on that key call other methods, ` +
          `so this change is reached from a queue worker, a cron job or another service rather than a request`
        : `${changedMethods ? `${changedMethods} changed; ` : ""}no route reaches it within ${options.maxDepth} ` +
          `import hops and it is not wired to a service key`;

      if (project.source === "unowned") {
        unowned.push({ file, reason: "no graph community, no service wiring, and no route reaches it" });
      } else {
        noRouteImpact.push({ file, project: project.name, reason });
      }
      continue;
    }

    let output = byProject.get(project.id);
    if (!output) {
      output = {
        project_id: project.id,
        project_name: project.name,
        source: project.source,
        matched_by: project.matched_by,
        owner: project.definition?.owner,
        team: project.definition?.team,
        slack: project.definition?.slack,
        jira: project.definition?.jira,
        status: project.definition?.status,
        launch_date: project.definition?.launch_date,
        max_risk: "low",
        headline: "",
        changed_files: [],
        changed_code: [],
        module_only_routes: 0,
        narrowing_notes: [],
        impacted_routes: { direct: [], indirect_di: [], indirect_graph: [] },
        changes: [],
        narratives: [],
        wide_impact: [],
        action_items: []
      };
      byProject.set(project.id, output);
      definitions.set(project.id, project.definition);
    }

    output.changed_files.push(file);
    output.module_only_routes += impact.module_only_routes ?? 0;
    for (const note of impact.narrowing_notes ?? []) {
      if (!output.narrowing_notes.includes(note)) output.narrowing_notes.push(note);
    }
    // A focus with neither a resolved method nor a classified line has nothing a reader can act
    // on, and every route file would otherwise contribute one "no factory found" line.
    if (impact.focus && (impact.focus.methods.length || impact.focus.categories.length)) {
      output.changed_code.push(impact.focus);
    }

    // Two files in the same service module both reach that service's routes, so without this the
    // route is listed once per changed file. Attribution is per project, not per file: a route
    // that two different projects reach is still worth reporting to both.
    const seen = seenByProject.get(project.id) ?? new Set<string>();
    seenByProject.set(project.id, seen);

    for (const route of impact.direct) {
      if (seen.has(route.route)) continue;
      seen.add(route.route);
      output.impacted_routes.direct.push(route);
      output.changes.push(route);
      output.narratives.push({ route: route.route, kind: route.kind, narrative: narrateDirect(route, project) });
    }
    for (const route of impact.indirect) {
      if (seen.has(route.route)) continue;
      seen.add(route.route);
      if (route.kind === "indirect_di") output.impacted_routes.indirect_di.push(route);
      else output.impacted_routes.indirect_graph.push(route);
      output.narratives.push({ route: route.route, kind: route.kind, narrative: narrateIndirect(route) });
    }

    if (impact.wide) {
      const entry = { ...impact.wide, file };
      output.wide_impact.push(entry);
      wideFiles.push({ ...entry, project: project.name });
    }
  }

  for (const output of byProject.values()) {
    const risks: Risk[] = [
      ...output.impacted_routes.direct.map((route) => route.risk),
      ...output.impacted_routes.indirect_di.map((route) => route.risk),
      ...output.impacted_routes.indirect_graph.map((route) => route.risk),
      // Reaching most of the API is itself worth a look, even when the edit looks trivial.
      ...output.wide_impact.map((): Risk => "medium"),
      // An access decision changing is the case both halves of this tool are blind to: no route
      // signature moves, and the route list looks the same as any other service edit. Lifting the
      // project (not every route on it) is what puts it at the top of the report.
      ...output.changed_code.filter(hasAuthorizationChange).map((): Risk => "high")
    ];
    output.max_risk = maxRisk(risks.length ? risks : ["low"]);
    output.changed_files.sort();
    output.headline = buildHeadline(output);
    output.action_items = buildActionItems(output, definitions.get(output.project_id), now);
  }

  const projects = [...byProject.values()].sort(
    (a, b) =>
      RISK_ORDER[b.max_risk] - RISK_ORDER[a.max_risk] ||
      b.impacted_routes.direct.length - a.impacted_routes.direct.length ||
      a.project_name.localeCompare(b.project_name)
  );

  const totals = projects.reduce(
    (acc, project) => ({
      direct: acc.direct + project.impacted_routes.direct.length,
      indirect: acc.indirect + project.impacted_routes.indirect_di.length + project.impacted_routes.indirect_graph.length,
      executing: acc.executing + project.impacted_routes.indirect_di.filter((route) => route.precision === "method").length,
      moduleOnly: acc.moduleOnly + project.module_only_routes
    }),
    { direct: 0, indirect: 0, executing: 0, moduleOnly: 0 }
  );

  const refusals = [...focuses.values()]
    .filter((focus) => !focus.narrowed)
    .map((focus) => ({ file: focus.file, reason: focus.reason ?? "" }));

  const analysis: Analysis = {
    meta: {
      generated_at: now.toISOString(),
      report: { scope: report.scope, base: report.meta?.base, head: report.meta?.head, pr: report.meta?.pr },
      manifest: { revision: manifest._meta?.revision, route_count: manifest._meta?.route_count },
      graph: graph ? { commit: graph.commit, nodes: graph.nodeCount, edges: graph.edgeCount } : null,
      di_bridge: { service_keys: di.byKey.size, unresolved: di.unresolved },
      narrowing: {
        available: Boolean(report.meta?.changed_hunks && report.meta?.head),
        files_with_hunks: focuses.size,
        narrowed: focuses.size - refusals.length,
        refused: refusals,
        // Files resolving to methods is not the same as reach being narrowed: the key is only
        // narrowed when the bound module file is the sole changed file mapping to it.
        keys_considered: narrowing.size,
        keys_narrowed: [...narrowing.values()].filter((decision) => decision.methods).length,
        keys_refused: [...narrowing.entries()]
          .filter(([, decision]) => !decision.methods)
          .map(([key, decision]) => ({ key, reason: decision.reason ?? "" }))
      },
      thresholds: options
    },
    summary: {
      changed_files: changedFiles.length,
      analysed_files: analysable.length,
      direct_routes: totals.direct,
      indirect_routes: totals.indirect,
      executing_routes: totals.executing,
      module_only_routes: totals.moduleOnly,
      wide_impact_files: wideFiles.length,
      projects_affected: projects.length,
      max_risk: projects.length ? projects[0].max_risk : "low"
    },
    affected_projects: projects,
    wide_impact_files: wideFiles,
    no_route_impact: noRouteImpact,
    unowned_changes: unowned,
    skipped_files: skipped
  };

  // Only meaningful against a real registry: listing the hundreds of graph communities a change
  // did not touch would be noise, not information.
  if (registry) {
    analysis.unaffected_projects = Object.entries(registry.projects)
      .filter(([id]) => !byProject.has(id))
      .map(([id, definition]) => ({ project_id: id, project_name: definition.name }));
  }

  return analysis;
};

