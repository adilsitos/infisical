type Risk = "critical" | "high" | "medium" | "low";

const RISK_ORDER: Record<Risk, number> = { critical: 4, high: 3, medium: 2, low: 1 };

const maxRisk = (risks: Risk[]): Risk =>
  risks.reduce<Risk>((worst, risk) => (RISK_ORDER[risk] > RISK_ORDER[worst] ? risk : worst), "low");

interface Scored {
  risk: Risk;
  reasons: string[];
}

// Every rule states its own reason, so a score can always be traced back to the field that caused
// it. A route the reader cannot audit is a route they will learn to ignore.
const scoreDirectChange = (
  status: "changed" | "added" | "removed",
  details: ChangeDetail[],
  after: BehavioralSignature
): Scored => {
  const reasons: string[] = [];
  const risks: Risk[] = [];
  const detailOf = (field: string) => details.find((detail) => detail.field === field);

  if (status === "removed") {
    return { risk: "critical", reasons: ["the route no longer exists, so every caller of it breaks"] };
  }

  const auth = detailOf("auth_modes");
  if (auth?.removed.length) {
    risks.push("critical");
    reasons.push(`accepted auth modes dropped ${auth.removed.join(", ")}, which can lock callers out or widen access`);
  }
  if (auth?.added.length) {
    risks.push("high");
    reasons.push(`the route now also accepts ${auth.added.join(", ")}`);
  }

  const hooks = detailOf("hooks");
  if (hooks?.removed.some((hook) => hook.includes("verifyAuth"))) {
    risks.push("critical");
    reasons.push("an onRequest:verifyAuth hook was removed, so the route may no longer be authenticated");
  } else if (hooks?.removed.length) {
    risks.push("high");
    reasons.push(`lifecycle hooks removed: ${hooks.removed.join(", ")}`);
  }
  if (detailOf("hooks (reordered)")) {
    risks.push("critical");
    reasons.push("lifecycle hooks were reordered, which changes what runs before the handler");
  }

  for (const field of ["method", "url"] as const) {
    const detail = detailOf(field);
    if (detail) {
      risks.push("high");
      reasons.push(`${field} changed from ${detail.removed.join("") || "(none)"} to ${detail.added.join("") || "(none)"}, which breaks existing callers`);
    }
  }

  if (detailOf("response_schema")) {
    risks.push("high");
    reasons.push("the response schema changed, so clients parsing this response may break");
  }

  for (const field of ["params_fields", "body_fields", "query_fields"] as const) {
    const detail = detailOf(field);
    if (detail?.removed.length) {
      risks.push("high");
      reasons.push(`${field.replace("_fields", "")} field(s) removed: ${detail.removed.join(", ")}`);
    }
    if (detail?.added.length) {
      risks.push("low");
      reasons.push(`${field.replace("_fields", "")} field(s) added: ${detail.added.join(", ")}`);
    }
  }

  const rateLimit = detailOf("rate_limit");
  if (rateLimit) {
    const relaxed = rateLimit.removed.includes("writeLimit") && rateLimit.added.includes("readLimit");
    risks.push(relaxed ? "high" : "medium");
    reasons.push(
      `rate limit changed from ${rateLimit.removed.join("") || "(none)"} to ${rateLimit.added.join("") || "(none)"}` +
        (relaxed ? ", which relaxes a write path to read limits" : "")
    );
  }

  const serviceCalls = detailOf("service_calls");
  if (serviceCalls?.added.length) {
    risks.push("medium");
    reasons.push(`the handler now calls ${serviceCalls.added.join(", ")}`);
  }
  if (serviceCalls?.removed.length) {
    risks.push("high");
    reasons.push(`the handler no longer calls ${serviceCalls.removed.join(", ")}`);
  }

  const cross = detailOf("cross_module_deps");
  if (cross?.added.length) {
    risks.push("medium");
    reasons.push(`new dependencies on ${[...new Set(cross.added.map((dep) => dep.split(":")[0]))].join(", ")}`);
  }

  if (status === "added") {
    risks.push("medium");
    reasons.push("this is a new public endpoint, so it needs auth, validation and rate-limit review");
  }

  if (after.file.startsWith("src/ee/")) {
    risks.push("high");
    reasons.push("the route is enterprise-gated, so a regression is licence-visible");
  }

  if (!reasons.length) reasons.push("the signature moved without any field this analyzer scores");
  return { risk: maxRisk(risks.length ? risks : ["low"]), reasons };
};

