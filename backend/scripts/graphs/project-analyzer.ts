interface Options {
  wideThreshold: number;
  maxDepth: number;
}

// The head revision, never the working tree: the analyzer runs on a checkout that does not contain
// an open pull request's commits, so its line numbers would land in the wrong function. A file the
// head does not have (a deletion) simply gets no focus and keeps file-level reach.
const buildFocuses = (report: DiffReport, files: string[]): Map<string, ChangeFocus> => {
  const focuses = new Map<string, ChangeFocus>();
  const hunks = report.meta?.changed_hunks;
  const head = report.meta?.head;
  if (!hunks || !head) return focuses;

  for (const file of files) {
    const ranges = hunks[file];
    if (!ranges?.length) continue;
    const text = readAtRevision(head, file);
    if (!text) continue;
    focuses.set(file, focusChange(file, text, ranges));
  }

  return focuses;
};

interface KeyNarrowing {
  methods?: FocusMethod[];
  reason?: string;
}

// Decided per service key, once, before any file is analysed - never per changed file. Two reasons:
//
//   - Soundness. Narrowing to the methods that changed in the bound module file is only honest if
//     that file is the ONLY changed file mapping to the key. If a dal, fns or queue file in the
//     same module also changed, a route calling an untouched service method can still change
//     behaviour through it, and excluding that route would be a false negative.
//   - Determinism. Changed files are analysed in sorted order and the first one to claim a route
//     wins, so a per-file decision let audit-report-dal.ts claim a route at module precision
//     before audit-report-service.ts could claim it at method precision. Same input, worse answer,
//     for no reason other than the alphabet.
const buildKeyNarrowing = (files: string[], di: DiBridge, focuses: Map<string, ChangeFocus>): Map<string, KeyNarrowing> => {
  const filesByKey = new Map<string, string[]>();
  for (const file of files) {
    for (const key of di.keysForFile(file)) {
      const bucket = filesByKey.get(key);
      if (bucket) bucket.push(file);
      else filesByKey.set(key, [file]);
    }
  }

  const narrowing = new Map<string, KeyNarrowing>();
  const shortName = (file: string): string => file.split("/").pop() ?? file;

  for (const [key, changed] of filesByKey) {
    const bound = di.byKey.get(key)?.moduleFile;
    if (!bound) continue;

    const focus = bound ? focuses.get(bound) : undefined;
    if (focus) focus.di_bound = true;

    if (!changed.includes(bound)) {
      narrowing.set(key, {
        reason:
          `${capped(changed.map(shortName), 3)} changed, which the service module uses rather than the file the key is ` +
          `bound to, so its callers cannot be resolved to methods`
      });
      continue;
    }
    if (changed.length > 1) {
      narrowing.set(key, {
        reason:
          `${capped(changed.filter((file) => file !== bound).map(shortName), 3)} in the same module also changed, and a ` +
          `route calling an untouched method can still change behaviour through those`
      });
      continue;
    }
    if (!focus) continue;
    if (!focus.narrowed) {
      narrowing.set(key, { reason: focus.reason });
      continue;
    }

    narrowing.set(key, { methods: focus.methods });
  }

  return narrowing;
};

const hasAuthorizationChange = (focus: ChangeFocus): boolean =>
  focus.categories.some((category) => category.category === AUTHORIZATION_CATEGORY);

const authorizationMethodsOf = (focus: ChangeFocus): string[] =>
  focus.methods
    .filter((method) => method.categories.some((category) => category.category === AUTHORIZATION_CATEGORY))
    .map((method) => method.name);

const analyzeFile = (
  file: string,
  view: ManifestView,
  di: DiBridge,
  graph: GraphIndex | null,
  directByFile: Map<string, RouteImpact[]>,
  focus: ChangeFocus | undefined,
  narrowing: Map<string, KeyNarrowing>,
  options: Options
): FileImpact => {
  const impact: FileImpact = {
    file,
    community: graph?.communityOfFile(file) ?? null,
    service_keys: di.keysForFile(file),
    direct: directByFile.get(file) ?? [],
    indirect: [],
    focus
  };

  const claimed = new Set(impact.direct.map((route) => route.route));
  const candidates: RouteImpact[] = [];
  const notes = new Set<string>();
  let moduleOnly = 0;

  // 1. DI reach. A service module's routes are invisible to the import graph, so this is the only
  //    path that finds them.
  //
  //    Narrowed to the changed methods when the changed file is the module the key is bound to and
  //    ./method-index.ts could resolve every hunk. Anything else (a dal or fns file in the same
  //    module, a hunk at module scope, an unresolvable helper) keeps the whole-key reach, because
  //    then the change really can surface through any method.
  for (const key of impact.service_keys) {
    const decision = narrowing.get(key);
    const narrowed = decision?.methods ?? null;
    const changedFor = new Map(narrowed?.map((method) => [method.name, method]) ?? []);
    if (!narrowed && decision?.reason) notes.add(decision.reason);

    for (const entry of view.routesByServiceKey.get(key) ?? []) {
      if (claimed.has(entry.route)) continue;

      if (narrowed) {
        const called = [...new Set(entry.signature.service_calls)]
          .filter((call) => call.startsWith(`${key}.`))
          .map((call) => call.slice(key.length + 1))
          .filter((method) => changedFor.has(method));

        if (!called.length) {
          moduleOnly += 1;
          continue;
        }

        const categories = called.flatMap((method) => changedFor.get(method)?.categories ?? []);
        const authorization = categories.find((category) => category.category === AUTHORIZATION_CATEGORY);
        const labels = [...new Set(categories.map((category) => category.label))];

        claimed.add(entry.route);
        candidates.push(
          toImpact(entry, "indirect_di", {
            risk: authorization ? "high" : "medium",
            reasons: [
              `this route executes ${called.map((method) => `server.services.${key}.${method}`).join(", ")}, which this change edits` +
                (labels.length ? ` (${labels.join("; ")})` : "") +
                " - its own signature did not move, so the gate cannot see this"
            ]
          }, { service_key: key, service_methods: called.sort(), precision: "method" })
        );
        continue;
      }

      claimed.add(entry.route);
      candidates.push(
        toImpact(entry, "indirect_di", {
          risk: "medium",
          reasons: [
            `this route calls server.services.${key}, which is wired to the changed module - its signature did not move, so the gate cannot see this`
          ]
        }, { service_key: key, precision: "module" })
      );
    }
  }

  if (moduleOnly) impact.module_only_routes = moduleOnly;
  if (notes.size) impact.narrowing_notes = [...notes];

  // 2. Graph reach, for everything the DI bridge does not cover (lib, helpers, plugins).
  if (graph) {
    const closure = graph.reverseClosure(file, options.maxDepth);
    for (const [reachedFile, entry] of closure) {
      if (!view.routeFiles.has(reachedFile)) continue;
      // routes/index.ts constructs every service, so it reaches all of them. It also happens to
      // declare one route (/api/status), which would otherwise be reported as impacted by every
      // service change in the repo. The edge is the wiring, not a dependency of that route.
      if (reachedFile === ROUTES_INDEX && file !== ROUTES_INDEX) continue;
      const chain = graph.chainTo(reachedFile, closure, file);
      const evidence: string[] = [];
      for (let i = 0; i < chain.length - 1; i += 1) {
        const [edge] = graph.edgesBetween(chain[i], chain[i + 1]);
        if (edge) evidence.push(`${edge.from}${edge.location ? `:${edge.location}` : ""} ${edge.relation} ${edge.to}`);
      }

      for (const route of view.routesByFile.get(reachedFile) ?? []) {
        if (claimed.has(route.route)) continue;
        claimed.add(route.route);
        candidates.push(
          toImpact(route, "indirect_graph", {
            risk: entry.depth === 1 ? "medium" : "low",
            reasons: [
              `its route file reaches the changed file in ${entry.depth} import hop${entry.depth === 1 ? "" : "s"}`
            ]
          }, { depth: entry.depth, chain, evidence })
        );
      }
    }
  }

  // A foundational file reaches most of the API. Enumerating that tells the reader nothing they
  // did not already know, and buries the changes that matter, so past the threshold it collapses
  // to a count plus the subsystems involved.
  const reachedFiles = new Set(candidates.map((route) => route.file));
  if (candidates.length > options.wideThreshold) {
    impact.wide = {
      reason:
        impact.service_keys.length && candidates.some((route) => route.kind === "indirect_di")
          ? `service key(s) ${impact.service_keys.join(", ")} are called by ${candidates.length} routes`
          : `${candidates.length} routes reach this file within ${options.maxDepth} import hops`,
      route_count: candidates.length,
      route_file_count: reachedFiles.size,
      subsystems: subsystemBreakdown(candidates, graph)
    };
  } else {
    impact.indirect = candidates.sort((a, b) => a.route.localeCompare(b.route));
  }

  return impact;
};

