const RISK_LABEL: Record<Risk, string> = { critical: "[!!!]", high: "[!!]", medium: "[!]", low: "[.]" };

const cell = (value: string): string => value.replace(/\|/g, "\\|");

const renderMarkdown = (analysis: Analysis): string => {
  const lines: string[] = ["## Project impact", ""];
  const meta = analysis.meta.report as { pr?: { slug: string; number: number }; base?: string; head?: string };

  if (meta.pr) lines.push(`Pull request \`${meta.pr.slug}#${meta.pr.number}\`.`);
  const executing = analysis.summary.executing_routes as number;
  const moduleOnly = analysis.summary.module_only_routes as number;
  lines.push(
    `${analysis.summary.analysed_files} changed file(s) analysed. ` +
      `${analysis.summary.direct_routes} route(s) changed signature, ` +
      `${analysis.summary.indirect_routes} more are reached indirectly and move no hash` +
      (executing ? `, ${executing} of which execute a changed method` : "") +
      `.` +
      (moduleOnly
        ? ` ${moduleOnly} further route(s) share a service key with the change but call methods it does not touch, and are not listed.`
        : ""),
    ""
  );

  if (!analysis.affected_projects.length) {
    lines.push("No project-level impact detected.", "");
    if (analysis.no_route_impact.length) {
      lines.push("**Changed files with no route reach**", "");
      for (const item of analysis.no_route_impact.slice(0, 10)) lines.push(`- \`${item.file}\` - ${item.reason}`);
      if (analysis.no_route_impact.length > 10) lines.push(`- ...and ${analysis.no_route_impact.length - 10} more`);
      lines.push("");
    }
    return lines.join("\n");
  }

  lines.push(
    "| Project | Risk | Changed routes | Indirect | Owner |",
    "| --- | --- | --- | --- | --- |"
  );
  for (const project of analysis.affected_projects) {
    const indirect = project.impacted_routes.indirect_di.length + project.impacted_routes.indirect_graph.length;
    lines.push(
      `| ${cell(project.project_name)} | ${project.max_risk} | ${project.impacted_routes.direct.length} | ${indirect} | ${cell(project.owner ?? "-")} |`
    );
  }
  lines.push("");

  for (const project of analysis.affected_projects) {
    lines.push(`<details><summary><b>${cell(project.project_name)}</b> - ${project.max_risk} - ${cell(project.headline)}</summary>`, "");

    if (project.action_items.length) {
      lines.push("**Actions**", "");
      for (const item of project.action_items) {
        lines.push(`- \`${item.priority}\` ${item.action}${item.assignee ? ` (${item.assignee})` : ""}`);
      }
      lines.push("");
    }

    if (project.changed_code.length) {
      lines.push("**Changed code**", "");
      for (const focus of project.changed_code) {
        lines.push(`- \`${focus.file}\` - ${cell(methodSummary(focus, false))}`);
        for (const category of focus.categories) lines.push(`  - ${category.label}: \`${cell(category.evidence)}\``);
      }
      lines.push("");
    }

    if (project.impacted_routes.direct.length) {
      lines.push("**Routes whose behaviour changed**", "");
      for (const route of project.impacted_routes.direct) {
        lines.push(`- \`${route.method} ${route.url}\` (${route.status}, ${route.risk}) - ${route.reasons.join("; ")}`);
      }
      lines.push("");
    }

    const indirect = [...project.impacted_routes.indirect_di, ...project.impacted_routes.indirect_graph];
    if (indirect.length) {
      lines.push("**Reached indirectly (no signature change - the behaviour gate cannot see these)**", "");
      for (const route of indirect.slice(0, 25)) {
        const how =
          route.precision === "method"
            ? `executes ${route.service_methods?.map((method) => `\`${route.service_key}.${method}\``).join(", ")}`
            : route.kind === "indirect_di"
              ? `via server.services.${route.service_key}`
              : `${route.depth} import hop(s)`;
        lines.push(`- \`${route.method} ${route.url}\` - ${how}`);
      }
      if (indirect.length > 25) lines.push(`- ...and ${indirect.length - 25} more`);
      if (project.module_only_routes) {
        lines.push(
          `- ${project.module_only_routes} route(s) on the same service key call methods this change does not touch, and are not listed`
        );
      }
      lines.push("");
    }

    if (project.wide_impact.length) {
      lines.push("**Foundational files (reach capped)**", "");
      for (const wide of project.wide_impact) {
        lines.push(`- \`${wide.file}\` - ${wide.reason}; subsystems: ${wide.subsystems.map((s) => `${s.community} (${s.routes})`).join(", ")}`);
      }
      lines.push("");
    }

    lines.push(`Changed files: ${project.changed_files.map((file) => `\`${file}\``).join(", ")}`, "", "</details>", "");
  }

  if (analysis.unowned_changes.length) {
    lines.push("**Unowned changes**", "");
    for (const item of analysis.unowned_changes) lines.push(`- \`${item.file}\` - ${item.reason}`);
    lines.push("");
  }

  return lines.join("\n");
};

const printSummary = (analysis: Analysis): void => {
  console.log("\n  Project Impact Analysis\n");

  // "No impact" is a claim, not an answer. What a reader needs is which file was analysed and what
  // stopped it reaching a route, or they cannot tell a genuinely internal change from a hole in
  // the tool's wiring.
  if (!analysis.affected_projects.length) {
    console.log("  No project-level impact detected.\n");
    for (const item of analysis.no_route_impact.slice(0, 8)) {
      console.log(`  [.] ${item.file}`);
      console.log(`      ${item.reason}`);
    }
    if (analysis.no_route_impact.length > 8) {
      console.log(`  [.] ...and ${analysis.no_route_impact.length - 8} more file(s)`);
    }
    if (analysis.no_route_impact.length) console.log("");
  }

  for (const project of analysis.affected_projects) {
    console.log(`  ${RISK_LABEL[project.max_risk]} ${project.project_name}`);
    console.log(`      ${project.headline}`);
    const features = [
      ...new Set(
        [
          ...project.impacted_routes.direct,
          ...project.impacted_routes.indirect_di,
          ...project.impacted_routes.indirect_graph
        ].map((route) => route.feature)
      )
    ].sort();
    for (const focus of project.changed_code.slice(0, 4)) console.log(`      changed code: ${methodSummary(focus)}`);
    if (project.changed_code.length > 4) {
      console.log(`      changed code: ...and ${project.changed_code.length - 4} more file(s)`);
    }
    if (features.length) console.log(`      features: ${features.join(", ")}`);
    if (project.owner || project.team) console.log(`      owner: ${project.owner ?? "-"} | team: ${project.team ?? "-"}`);
    for (const item of project.action_items) console.log(`      -> [${item.priority}] ${item.action}`);
    console.log("");
  }

  for (const wide of analysis.wide_impact_files) {
    console.log(`  [~] ${wide.file}: ${wide.reason} (not enumerated)`);
  }
  if (analysis.wide_impact_files.length) console.log("");

  const narrowing = (analysis.meta.narrowing ?? {}) as {
    available?: boolean;
    narrowed?: number;
    files_with_hunks?: number;
    keys_narrowed?: number;
    keys_considered?: number;
  };
  console.log(
    `  Summary: ${analysis.summary.direct_routes} route(s) changed, ${analysis.summary.indirect_routes} reached indirectly ` +
      `(${analysis.summary.executing_routes} executing a changed method), ` +
      `${analysis.summary.module_only_routes} untouched on the same service key(s), ` +
      `${analysis.summary.projects_affected} project(s) affected`
  );
  if (narrowing.available) {
    console.log(
      `  Method narrowing: ${narrowing.narrowed}/${narrowing.files_with_hunks} changed file(s) resolved to methods, ` +
        `${narrowing.keys_narrowed}/${narrowing.keys_considered} service key(s) narrowed`
    );
  } else {
    console.log(
      "  Method narrowing: unavailable (this report carries no changed_hunks; regenerate it with the current behavior:pr)"
    );
  }
};

