interface ResolvedProject {
  id: string;
  name: string;
  source: "registry" | "router" | "community" | "unowned";
  matched_by?: string;
  definition?: ProjectDef;
}

const titleCase = (value: string): string =>
  value
    .split(/[-/]/)
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");

// Graphify's community names are good for service modules ("Alerting Module Core", "PAM Accounts
// & Rotation") and unreliable for route files, because Leiden groups routers by their shared
// schema and rate-limit imports rather than by domain - which is how insights-router.ts ends up
// in a community named after ACME. A router names its own domain, so for route files that beats
// the community every time, and it is stable across graphify runs.
const routerProject = (file: string): { id: string; name: string } | null => {
  if (!file.includes("/routes/")) return null;

  const stem = path.posix.basename(file).replace(/\.tsx?$/, "").replace(/-(router|routers|endpoints)$/, "");
  if (stem === "index") {
    const segments = path.posix.dirname(file).split("/").slice(-2).join("/");
    return { id: `router:${segments}`, name: titleCase(segments) };
  }
  return { id: `router:${stem}`, name: titleCase(stem) };
};

const resolveProject = (impact: FileImpact, registry: ProjectRegistry | null): ResolvedProject => {
  for (const [id, definition] of Object.entries(registry?.projects ?? {})) {
    if (definition.path_globs?.some((pattern) => matchesGlob(impact.file, pattern))) {
      return { id, name: definition.name, source: "registry", matched_by: "path_globs", definition };
    }
  }
  for (const [id, definition] of Object.entries(registry?.projects ?? {})) {
    if (definition.service_keys?.some((key) => impact.service_keys.includes(key))) {
      return { id, name: definition.name, source: "registry", matched_by: "service_keys", definition };
    }
  }
  for (const [id, definition] of Object.entries(registry?.projects ?? {})) {
    if (impact.community && definition.communities?.includes(impact.community.name)) {
      return { id, name: definition.name, source: "registry", matched_by: "communities", definition };
    }
  }

  const router = routerProject(impact.file);
  if (router) {
    return { id: router.id, name: router.name, source: "router", matched_by: "the router file's own name" };
  }

  if (impact.community) {
    return {
      id: `community:${impact.community.id}`,
      name: impact.community.name || `Community ${impact.community.id}`,
      source: "community",
      matched_by: "graph community of the changed file"
    };
  }

  return { id: "unowned", name: "Unowned", source: "unowned" };
};

