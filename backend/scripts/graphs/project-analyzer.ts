interface ActionItem {
  priority: Risk;
  action: string;
  assignee?: string;
}

const buildActionItems = (
  project: ProjectOutput,
  definition: ProjectDef | undefined,
  now: Date
): ActionItem[] => {
  const items: ActionItem[] = [];
  const owner = definition?.owner;

  const authChanges = project.changes.filter((route) =>
    route.reasons.some((reason) => reason.includes("auth mode") || reason.includes("verifyAuth") || reason.includes("hooks"))
  );
  if (authChanges.length) {
    items.push({
      priority: "critical",
      action: `Review the auth surface on ${authChanges.map((route) => `${route.method} ${route.url}`).join(", ")} before merging.`,
      assignee: owner
    });
  }

  const contractChanges = project.changes.filter((route) =>
    route.reasons.some((reason) => reason.includes("breaks existing callers") || reason.includes("clients parsing"))
  );
  if (contractChanges.length) {
    items.push({
      priority: "high",
      action:
        `${contractChanges.length} route(s) changed their request or response contract. Adding an optional field is safe; ` +
        `renaming one, tightening validation or changing a status code is not - version the route instead.`,
      assignee: owner
    });
  }

  const routeList = (routes: RouteImpact[], limit = 5): string =>
    `${routes.slice(0, limit).map((route) => `${route.method} ${route.url}`).join(", ")}${routes.length > limit ? `, and ${routes.length - limit} more` : ""}`;

  // Authorization first, and named as the finding rather than buried in a coverage nudge. A
  // permission change moves no signature, so this is the one thing in the report that the gate
  // alone would have reported as "no behaviour change".
  const authorizationFiles = project.changed_code.filter(hasAuthorizationChange);
  if (authorizationFiles.length) {
    const methods = [...new Set(authorizationFiles.flatMap(authorizationMethodsOf))];
    const executing = project.impacted_routes.indirect_di.filter((route) =>
      route.service_methods?.some((method) => methods.includes(method))
    );
    const where = methods.length
      ? `in ${capped(methods.map((method) => `\`${method}\``), 5)}`
      : `in ${capped(authorizationFiles.map((focus) => `\`${focus.file.split("/").pop()}\``), 3)}`;

    items.push({
      priority: "high",
      action:
        `An access-control decision changed ${where}. Exercise both the allow and the deny path` +
        `${executing.length ? ` on ${routeList(executing)}` : ""}: a permission change moves no route signature, so no ` +
        `other check in this report can catch a regression.`,
      assignee: owner
    });
  }

  const executes = project.impacted_routes.indirect_di.filter((route) => route.precision === "method");
  const moduleWide = project.impacted_routes.indirect_di.filter((route) => route.precision !== "method");

  if (executes.length) {
    const untouched = project.module_only_routes
      ? ` The other ${project.module_only_routes} route(s) on this service key call methods this change does not touch.`
      : "";
    items.push({
      priority: "medium",
      action:
        (executes.length === 1
          ? `${routeList(executes)} executes changed code with no signature change of its own, so the behaviour gate is ` +
            `blind to it. Confirm it has test coverage.`
          : `${executes.length} routes execute changed code with no signature change of their own, so the behaviour gate ` +
            `is blind to them. Confirm coverage on ${routeList(executes)}.`) + untouched,
      assignee: owner
    });
  }

  if (moduleWide.length) {
    // Why the list is this wide matters as much as the list: a reader who knows it could not be
    // narrowed treats it as a reach set, and a reader who does not treats it as an impact set.
    const why = project.narrowing_notes.length ? ` Not narrowed to a method: ${project.narrowing_notes[0]}.` : "";

    items.push({
      priority: "medium",
      action:
        `${moduleWide.length} route(s) call into the changed service module but have no signature change, so the behaviour ` +
        `gate is blind to them. Confirm they have test coverage: ${routeList(moduleWide)}.${why}`,
      assignee: owner
    });
  }

  if (definition?.slack) {
    items.push({
      priority: "medium",
      action: `Notify ${definition.team ? `${definition.team} ` : ""}in ${definition.slack}.`,
      assignee: owner
    });
  }

  if (definition?.launch_date) {
    const launch = new Date(`${definition.launch_date}T00:00:00Z`);
    const days = Math.ceil((launch.getTime() - now.getTime()) / 86_400_000);
    if (days > 0 && days <= 14) {
      items.push({
        priority: "high",
        action: `This project launches in ${days} day(s) (${definition.launch_date}); behavioural changes this close to launch need extra scrutiny.`,
        assignee: owner
      });
    }
  }

  return items;
};

