const narrateDirect = (route: RouteImpact, project: ResolvedProject): string => {
  const paragraphs: string[] = [];

  if (route.status === "changed") {
    paragraphs.push(
      `\`${route.method} ${route.url}\` in \`${route.file}\` changed behaviour: its signature hash moved ` +
        `from \`${route.hash_before}\` to \`${route.hash_after}\`.`
    );
  } else if (route.status === "added") {
    paragraphs.push(`\`${route.method} ${route.url}\` is a new endpoint in \`${route.file}\`.`);
  } else {
    paragraphs.push(`\`${route.method} ${route.url}\` was removed from \`${route.file}\`.`);
  }

  paragraphs.push(route.reasons.map((reason) => reason[0].toUpperCase() + reason.slice(1)).join(". ") + ".");
  paragraphs.push(`This lands in "${project.name}", matched by ${project.matched_by}.`);

  return paragraphs.join("\n\n");
};

const narrateIndirect = (route: RouteImpact): string => {
  if (route.kind === "indirect_di") {
    return (
      `\`${route.method} ${route.url}\` (\`${route.file}\`) calls \`server.services.${route.service_key}\`. ` +
      `The changed file is part of that service module, so this route's behaviour can move even though its ` +
      `own text - and therefore its signature hash - did not.`
    );
  }
  const trace = route.evidence?.length ? ` Path: ${route.evidence.join("; ")}.` : "";
  return (
    `\`${route.method} ${route.url}\` (\`${route.file}\`) reaches the changed file in ${route.depth} import ` +
    `hop${route.depth === 1 ? "" : "s"}.${trace}`
  );
};

