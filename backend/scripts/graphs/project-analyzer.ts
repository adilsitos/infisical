/**
 * Project Impact Analyzer
 * =======================
 * Answers "which projects and features does this change affect, and what should each owner know?"
 * by joining three artifacts that already exist:
 *
 *   1. the diff report from ./pr-behavior-diff.ts  - which route signatures moved, and the full
 *                                                    list of changed backend files
 *   2. .behavior-manifest.json                     - every route, its service calls, its imports
 *   3. graphify-out/graph.json                     - who reaches whom, and which subsystem a file
 *                                                    belongs to
 *
 * The reason this is a separate script rather than more output from the gate: the gate is
 * deliberately text-local. A route's hash is computed from its own file, which is what lets any
 * git revision be signed without a checkout - and which means a change inside a service moves no
 * hash at all. That is not a bug in the gate, it is the price of its portability. This script
 * pays the other side: it starts from the changed FILES and works forward to the routes they
 * reach, so a pull request touching only secret-service.ts still reports the routes behind it.
 *
 * Reach is established two ways, because neither alone is sufficient:
 *   - the DI bridge (./di-bridge.ts), for service modules, which the import graph cannot see
 *     through because routers reach services via `server.services.<key>`
 *   - the graph's reverse closure, for everything else (lib, helpers, plugins, shared fns)
 *
 * Both are capped. A change to src/lib/errors/index.ts reaches 471 route files; printing them is
 * not analysis. Past the threshold a file is reported as wide-impact with a count and the
 * subsystems involved.
 *
 * Ownership is auto-derived from graph communities so this works with no configuration. A
 * committed .behavior-projects.json overlays human metadata (owner, team, Slack) on top; see the
 * `discover-projects` command, which scaffolds one.
 *
 * Usage:
 *     npm run behavior:pr -- --url 7638 --report /tmp/report.json
 *     npm run behavior:analyze -- --report /tmp/report.json --markdown /tmp/impact.md
 *     npm run behavior:discover-projects
 */

