const commandDiscoverProjects = (graphPath: string, configPath: string, registryPath: string): void => {
  const config = loadConfig(configPath);
  const graph = loadGraphIndex(graphPath, config);
  if (!graph) fail(`No graph at '${graphPath}'. Run graphify first, or pass --graph.`);

  const di = loadDiBridge();

  // One project per community that owns a SERVICE module, seeded with the paths and service keys
  // that resolve to it. A human then fills in the metadata a graph cannot know.
  //
  // Route files are deliberately not scaffolded. Their communities are unreliable (Leiden groups
  // routers by shared schema imports, not by domain), and a glob wide enough to cover one -
  // src/ee/routes/v1/** - would then claim every router in that directory. Left out, they fall
  // through to the router-name derivation in the analyzer, which is both accurate and stable.
  const communities = new Map<string, { name: string; dirs: Set<string>; keys: Set<string> }>();

  const record = (file: string) => {
    const community = graph.communityOfFile(file);
    if (!community) return;
    const id = `community-${community.id}`;
    let entry = communities.get(id);
    if (!entry) {
      entry = { name: community.name || `Community ${community.id}`, dirs: new Set(), keys: new Set() };
      communities.set(id, entry);
    }
    entry.dirs.add(path.posix.dirname(file));
    for (const key of di.keysForFile(file)) entry.keys.add(key);
  };

  for (const binding of di.byKey.values()) record(binding.moduleFile);

  const slug = (name: string): string =>
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") || "unnamed";

  const projects: Record<string, ProjectDef> = {};
  for (const [, entry] of [...communities.entries()].sort((a, b) => a[1].name.localeCompare(b[1].name))) {
    // Collapse sibling directories to their module root so the globs stay readable and keep
    // matching after a file is added.
    const roots = [...new Set([...entry.dirs].map((dir) => dir.split("/").slice(0, dir.startsWith("src/ee") || dir.startsWith("src/server") ? 4 : 3).join("/")))];
    projects[slug(entry.name)] = {
      name: entry.name,
      owner: "",
      team: "",
      slack: "",
      jira: "",
      status: "",
      launch_date: "",
      path_globs: roots.sort().map((root) => `${root}/**`),
      service_keys: [...entry.keys].sort(),
      communities: [entry.name]
    };
  }

  const output = {
    _notes: REGISTRY_NOTES,
    analysis: { wide_threshold: DEFAULT_WIDE_THRESHOLD, max_depth: DEFAULT_MAX_DEPTH },
    projects
  };

  writeFileSync(registryPath, `${JSON.stringify(output, null, 2)}\n`);
  console.log(
    `\n  Registry scaffold written to ${path.relative(BACKEND_ROOT, registryPath)}\n` +
      `    Projects:     ${Object.keys(projects).length} (one per graph community that owns backend source)\n` +
      `    Service keys: ${di.byKey.size} wired${di.unresolved.length ? `, ${di.unresolved.length} unresolved` : ""}\n\n` +
      `  Fill in owner / team / slack, delete what you do not want tracked, then commit it.\n` +
      `  Community names are regenerated on every graphify run - prefer path_globs for anything durable.\n`
  );
};

