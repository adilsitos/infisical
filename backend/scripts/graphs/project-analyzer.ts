const USAGE = `Usage: tsx ./scripts/graphs/project-analyzer.ts [command] [options]

Commands:
  analyze             (default) join a diff report with the graph and report per-project impact
  discover-projects   scaffold .behavior-projects.json from the graph and the DI wiring

Options:
  --report PATH       diff report from behavior:pr / behavior:diff (required for analyze)
  --manifest PATH     route manifest (default: backend/.behavior-manifest.json)
  --graph PATH        graph.json (default: ../graphify-out/graph.json)
  --config PATH       behavior config (default: backend/.behavior-config.json)
  --registry PATH     project registry (default: backend/.behavior-projects.json, optional)
  --output PATH       analysis JSON to write (default: backend/project-analysis.json)
  --markdown PATH     also write a pull-request-ready markdown summary
  --wide-threshold N  routes past which a file is reported as a count (default: ${DEFAULT_WIDE_THRESHOLD})
  --max-depth N       import hops to follow back from a changed file (default: ${DEFAULT_MAX_DEPTH})
  --ci                exit 1 when any project is critical or high risk
  -h, --help          show this message

Example:
  npm run behavior:pr -- --url 7638 --report /tmp/report.json
  npm run behavior:analyze -- --report /tmp/report.json --markdown /tmp/impact.md
`;

const positiveInt = (value: string | undefined, fallback: number, flag: string): number => {
  if (value === undefined) return fallback;
  const parsed = Number(value);
  if (!Number.isInteger(parsed) || parsed < 1) fail(`${flag} must be a positive integer, got '${value}'.`);
  return parsed;
};

const main = (): void => {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      report: { type: "string" },
      manifest: { type: "string" },
      graph: { type: "string" },
      config: { type: "string" },
      registry: { type: "string" },
      output: { type: "string" },
      markdown: { type: "string" },
      "wide-threshold": { type: "string" },
      "max-depth": { type: "string" },
      ci: { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false }
    }
  });

  if (values.help) {
    console.log(USAGE);
    process.exit(0);
  }

  const graphPath = path.resolve(values.graph ?? DEFAULT_GRAPH);
  const configPath = path.resolve(values.config ?? DEFAULT_CONFIG);
  const manifestPath = path.resolve(values.manifest ?? DEFAULT_MANIFEST);
  const registryPath = path.resolve(values.registry ?? DEFAULT_REGISTRY);

  const command = positionals[0] ?? "analyze";
  if (command === "discover-projects") {
    commandDiscoverProjects(graphPath, configPath, registryPath);
    return;
  }
  if (command !== "analyze") fail(`Unknown command '${command}'.\n${USAGE}`);

  if (!values.report) {
    fail(
      `Pass --report <path>, the JSON written by \`npm run behavior:pr -- --report <path>\`.\n` +
        `Without it there is no set of changed files to analyse.\n${USAGE}`
    );
  }
  const reportPath = path.resolve(values.report);
  if (!existsSync(reportPath)) fail(`No diff report at '${reportPath}'.`);
  if (!existsSync(manifestPath)) {
    fail(
      `No route manifest at '${path.relative(BACKEND_ROOT, manifestPath)}'.\n` +
        `Run \`npm run behavior:build\` first - the analyzer needs it to know which routes call which service.`
    );
  }

  const report = JSON.parse(readFileSync(reportPath, "utf-8")) as DiffReport;
  const manifest = JSON.parse(readFileSync(manifestPath, "utf-8")) as Manifest;
  const config = loadConfig(configPath);
  const registry = loadRegistry(registryPath);
  const graph = loadGraphIndex(graphPath, config);
  const di = loadDiBridge();

  if (!graph) {
    console.warn(
      `  warn: no graph at ${graphPath}. Service reach still works via the DI wiring, but ` +
        `library and helper changes cannot be traced and grouping falls back to unowned.`
    );
  }
  if (!report.meta?.changed_files?.length) {
    console.warn(
      "  warn: this report carries no changed_files list, so only routes whose signature moved are " +
        "analysed. Regenerate it with the current behavior:pr to get service-level reach."
    );
  }
  if (di.unresolved.length) {
    console.warn(
      `  warn: ${di.unresolved.length} service key(s) could not be resolved to a module ` +
        `(${di.unresolved.map((entry) => entry.key).join(", ")}); routes calling them will not be reported as indirectly impacted.`
    );
  }

  const options: Options = {
    wideThreshold: positiveInt(values["wide-threshold"], registry?.analysis?.wide_threshold ?? DEFAULT_WIDE_THRESHOLD, "--wide-threshold"),
    maxDepth: positiveInt(values["max-depth"], registry?.analysis?.max_depth ?? DEFAULT_MAX_DEPTH, "--max-depth")
  };

  const analysis = analyze(report, manifest, config, graph, di, registry, options);

  const outputPath = path.resolve(values.output ?? DEFAULT_OUTPUT);
  writeFileSync(outputPath, `${JSON.stringify(analysis, null, 2)}\n`);
  if (values.markdown) writeFileSync(path.resolve(values.markdown), renderMarkdown(analysis));

  printSummary(analysis);
  console.log(`  Written: ${path.relative(BACKEND_ROOT, outputPath)}${values.markdown ? ` and ${values.markdown}` : ""}\n`);

  if (values.ci && RISK_ORDER[analysis.summary.max_risk as Risk] >= RISK_ORDER.high) process.exit(1);
};

if (require.main === module) main();
