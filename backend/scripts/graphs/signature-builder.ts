// Optional graph enrichment (never hashed)
// ---------------------------------------------------------------------------

interface GraphNodeRaw {
  id: string;
  label?: string;
  source_file?: string;
  community?: number;
  community_name?: string;
  _callable?: boolean;
}

interface GraphLinkRaw {
  source: string | { id: string };
  target: string | { id: string };
  relation?: string;
  confidence?: string;
}

interface GraphSummary {
  commit: string;
  nodes: number;
  edges: number;
  fileNodes: number;
  communities: number;
  relations: Record<string, number>;
  confidence: Record<string, number>;
  byFile: Map<string, { community: number | null; communityName: string }>;
  importDegree: { label: string; sourceFile: string; count: number }[];
}

const idOf = (value: string | { id: string }): string => (typeof value === "string" ? value : value.id);

const loadGraph = (graphPath: string): GraphSummary | null => {
  if (!existsSync(graphPath)) return null;

  const data = JSON.parse(readFileSync(graphPath, "utf-8")) as {
    nodes?: GraphNodeRaw[];
    links?: GraphLinkRaw[];
    edges?: GraphLinkRaw[];
    built_at_commit?: string;
  };

  const byId = new Map<string, GraphNodeRaw>();
  const byFile = new Map<string, { community: number | null; communityName: string }>();
  const communities = new Set<number | null>();

  for (const node of data.nodes ?? []) {
    byId.set(node.id, node);
    // community is an integer and 0 is a real community - never coerce it away.
    const community = typeof node.community === "number" ? node.community : null;
    communities.add(community);

    const sourceFile = node.source_file ?? "";
    const label = node.label ?? "";
    if (!sourceFile || node._callable) continue;
    const base = path.posix.basename(sourceFile);
    if (label === base || label.endsWith(`/${base}`)) {
      byFile.set(sourceFile, { community, communityName: node.community_name ?? "" });
    }
  }

  const links = data.links ?? data.edges ?? [];
  const relations: Record<string, number> = {};
  const confidence: Record<string, number> = {};
  const degree = new Map<string, number>();
  for (const link of links) {
    const relation = link.relation ?? "unknown";
    relations[relation] = (relations[relation] ?? 0) + 1;
    const conf = link.confidence ?? "EXTRACTED";
    confidence[conf] = (confidence[conf] ?? 0) + 1;
    if (relation === "imports" || relation === "imports_from") {
      const target = idOf(link.target);
      degree.set(target, (degree.get(target) ?? 0) + 1);
    }
  }

  const importDegree = [...degree.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 25)
    .map(([id, count]) => ({
      label: byId.get(id)?.label ?? id,
      sourceFile: byId.get(id)?.source_file ?? "",
      count
    }));

  return {
    commit: data.built_at_commit ?? "",
    nodes: byId.size,
    edges: links.length,
    fileNodes: byFile.size,
    communities: communities.size,
    relations: Object.fromEntries(Object.entries(relations).sort((a, b) => b[1] - a[1])),
    confidence: Object.fromEntries(Object.entries(confidence).sort((a, b) => b[1] - a[1])),
    byFile,
    importDegree
  };
};

export const loadAstHashes = (): Map<string, string> => {
  const hashes = new Map<string, string>();
  if (!existsSync(DEFAULT_GRAPHIFY_MANIFEST)) return hashes;
  const raw = JSON.parse(readFileSync(DEFAULT_GRAPHIFY_MANIFEST, "utf-8")) as Record<string, { ast_hash?: string }>;
  for (const [file, entry] of Object.entries(raw)) if (entry?.ast_hash) hashes.set(file, entry.ast_hash);
  return hashes;
};

const enrich = (entries: BehavioralSignature[], graph: GraphSummary | null): void => {
  if (!graph) return;
  const astHashes = loadAstHashes();
  for (const signature of entries) {
    const node = graph.byFile.get(signature.file);
    signature.graph = {
      community: node?.community ?? null,
      community_name: node?.communityName ?? "",
      ast_hash: astHashes.get(signature.file) ?? "",
      resolved: !!node
    };
  }
};

