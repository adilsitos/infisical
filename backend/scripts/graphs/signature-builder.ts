export interface CrossModuleDep {
  node: string;
  to: string;
  specifier: string;
}

interface FileImports {
  bindings: Set<string>;
  fileImports: string[];
  crossModuleDeps: CrossModuleDep[];
}

const readImports = (source: ts.SourceFile, relPath: string, config: BehaviorConfig): FileImports => {
  const ownModule = moduleOfFile(relPath);
  const noise = new Set(config.noise_bindings);

  const bindings = new Set<string>();
  const fileImports = new Set<string>();
  const crossByKey = new Map<string, CrossModuleDep>();

  for (const statement of source.statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    if (!ts.isStringLiteral(statement.moduleSpecifier)) continue;
    const specifier = statement.moduleSpecifier.text;

    const names: string[] = [];
    const clause = statement.importClause;
    if (clause) {
      if (clause.name) names.push(clause.name.text);
      if (clause.namedBindings) {
        if (ts.isNamespaceImport(clause.namedBindings)) names.push(clause.namedBindings.name.text);
        else for (const element of clause.namedBindings.elements) names.push(element.name.text);
      }
    }
    for (const name of names) bindings.add(name);

    const { moduleKey, sourcePath } = resolveSpecifier(specifier, relPath);
    if (sourcePath && isExcludedPath(sourcePath, config)) continue;

    for (const name of names) {
      if (noise.has(name)) continue;
      if (moduleKey === ownModule) {
        fileImports.add(name);
      } else {
        const key = `${moduleKey}:${name}`;
        if (!crossByKey.has(key)) crossByKey.set(key, { node: name, to: moduleKey, specifier });
      }
    }
  }

  return {
    bindings,
    fileImports: [...fileImports].sort(),
    crossModuleDeps: [...crossByKey.values()].sort((a, b) => `${a.to}:${a.node}`.localeCompare(`${b.to}:${b.node}`))
  };
};

const literalText = (node: ts.Node): string | null => {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  return null;
};

const propertyNamed = (obj: ts.ObjectLiteralExpression, name: string): ts.Expression | null => {
  for (const prop of obj.properties) {
    if (ts.isPropertyAssignment(prop) && prop.name && ts.isIdentifier(prop.name) && prop.name.text === name) {
      return prop.initializer;
    }
    if (ts.isShorthandPropertyAssignment(prop) && prop.name.text === name) return prop.name;
  }
  return null;
};

// Doc strings and formatting must not move a hash, but validator changes must. Comments and
// `.describe("...")` are stripped, then whitespace is collapsed, so reindenting or rewording a
// description is invisible while `.min(1)` -> `.min(8)` is not.
const stripDescribeCalls = (text: string): string => {
  let out = "";
  let index = 0;
  while (index < text.length) {
    const at = text.indexOf(".describe(", index);
    if (at === -1) {
      out += text.slice(index);
      break;
    }
    out += text.slice(index, at);
    let depth = 0;
    let cursor = at + ".describe".length;
    let quote: string | null = null;
    for (; cursor < text.length; cursor += 1) {
      const ch = text[cursor];
      if (quote) {
        if (ch === "\\") cursor += 1;
        else if (ch === quote) quote = null;
        continue;
      }
      if (ch === '"' || ch === "'" || ch === "`") quote = ch;
      else if (ch === "(") depth += 1;
      else if (ch === ")") {
        depth -= 1;
        if (depth === 0) {
          cursor += 1;
          break;
        }
      }
    }
    index = cursor;
  }
  return out;
};

const normalizeSchemaText = (text: string): string =>
  stripDescribeCalls(text)
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/[^\n]*/g, "")
    .replace(/\s+/g, " ")
    .trim();

const schemaDigest = (node: ts.Node | null, source: ts.SourceFile): string =>
  node ? createHash("sha256").update(normalizeSchemaText(node.getText(source))).digest("hex").slice(0, 8) : "";

// Top-level keys of the first object literal under a schema section, so a diff can name the
// field that was added rather than only showing a digest change.
const schemaFieldNames = (node: ts.Node | null): string[] => {
  if (!node) return [];
  let found: ts.ObjectLiteralExpression | null = null;
  const visit = (current: ts.Node): void => {
    if (found) return;
    if (ts.isObjectLiteralExpression(current)) {
      found = current;
      return;
    }
    ts.forEachChild(current, visit);
  };
  visit(node);
  if (!found) return [];
  const names = (found as ts.ObjectLiteralExpression).properties
    .map((prop) => (prop.name ? prop.name.getText() : ts.isSpreadAssignment(prop) ? "..." : ""))
    .filter(Boolean);
  return [...new Set(names)].sort();
};

const calleeName = (call: ts.CallExpression): string | null => {
  const target = call.expression;
  if (ts.isIdentifier(target)) return target.text;
  if (ts.isPropertyAccessExpression(target)) return target.name.text;
  return null;
};

// `server.services.<service>.<method>` and `req.server.services.<service>.<method>`
const serviceCallOf = (node: ts.Node): string | null => {
  if (!ts.isPropertyAccessExpression(node)) return null;
  const method = node.name.text;
  const mid = node.expression;
  if (!ts.isPropertyAccessExpression(mid)) return null;
  const service = mid.name.text;
  const base = mid.expression;
  if (ts.isPropertyAccessExpression(base) && base.name.text === "services") return `${service}.${method}`;
  if (ts.isIdentifier(base) && base.text === "services") return `${service}.${method}`;
  return null;
};

const rootIdentifier = (node: ts.Expression): string | null => {
  let cursor: ts.Expression = node;
  while (ts.isPropertyAccessExpression(cursor)) cursor = cursor.expression;
  return ts.isIdentifier(cursor) ? cursor.text : null;
};

const enclosingRegisterFn = (node: ts.Node): string => {
  let cursor: ts.Node | undefined = node;
  while (cursor) {
    if (ts.isVariableDeclaration(cursor) && ts.isIdentifier(cursor.name)) return cursor.name.text;
    if (ts.isFunctionDeclaration(cursor) && cursor.name) return cursor.name.text;
    cursor = cursor.parent;
  }
  return "";
};

interface RouteSite {
  line: number;
  methods: string[];
  url: string | null;
  rateLimit: string;
  authModes: string[];
  hooks: string[];
  serviceCalls: string[];
  serviceCallArgs: string[];
  localCalls: string[];
  bodyFields: string[];
  paramsFields: string[];
  queryFields: string[];
  responseCodes: string[];
  bodySchema: string;
  paramsSchema: string;
  querySchema: string;
  responseSchema: string;
  registerFn: string;
  operationId: string;
  hidden: boolean;
}

const readRouteObject = (
  obj: ts.ObjectLiteralExpression,
  call: ts.CallExpression,
  source: ts.SourceFile,
  relPath: string,
  imports: FileImports,
  config: BehaviorConfig,
  warn: (message: string) => void
): RouteSite | null => {
  const line = source.getLineAndCharacterOfPosition(call.getStart()).line + 1;

  // A spread means this is a re-dispatch wrapper (src/server/lib/with-route-prefix.ts), not a
  // route definition.
  if (obj.properties.some((prop) => ts.isSpreadAssignment(prop))) {
    warn(`skipped re-dispatch wrapper at ${relPath}:${line} (route object uses a spread)`);
    return null;
  }

  const methodNode = propertyNamed(obj, "method");
  const urlNode = propertyNamed(obj, "url");
  if (!methodNode || !urlNode) {
    warn(`skipped route at ${relPath}:${line} (no method/url property)`);
    return null;
  }

  let methods: string[] = [];
  const single = literalText(methodNode);
  if (single) methods = [single.toUpperCase()];
  else if (ts.isArrayLiteralExpression(methodNode)) {
    methods = methodNode.elements
      .map((element) => literalText(element))
      .filter((value): value is string => !!value)
      .map((value) => value.toUpperCase());
  }
  if (!methods.length) {
    warn(`skipped route at ${relPath}:${line} (method is not a literal or array of literals)`);
    return null;
  }

  const url = literalText(urlNode);
  if (!url) warn(`route at ${relPath}:${line} has a non-literal url; recorded as '${DYNAMIC_URL}'`);

  const configNode = propertyNamed(obj, "config");
  let rateLimit = "";
  if (configNode && ts.isObjectLiteralExpression(configNode)) {
    const limit = propertyNamed(configNode, "rateLimit");
    if (limit) rateLimit = limit.getText(source);
  }

  const schemaNode = propertyNamed(obj, "schema");
  let operationId = "";
  let hidden = false;
  let bodyNode: ts.Expression | null = null;
  let paramsNode: ts.Expression | null = null;
  let queryNode: ts.Expression | null = null;
  let responseNode: ts.Expression | null = null;
  if (schemaNode && ts.isObjectLiteralExpression(schemaNode)) {
    const op = propertyNamed(schemaNode, "operationId");
    if (op) operationId = literalText(op) ?? "";
    hidden = propertyNamed(schemaNode, "hide")?.kind === ts.SyntaxKind.TrueKeyword;
    bodyNode = propertyNamed(schemaNode, "body");
    paramsNode = propertyNamed(schemaNode, "params");
    queryNode = propertyNamed(schemaNode, "querystring");
    responseNode = propertyNamed(schemaNode, "response");
  }

  const hooks: string[] = [];
  const authModes = new Set<string>();
  for (const hookKey of config.hook_keys) {
    const hookNode = propertyNamed(obj, hookKey);
    if (!hookNode) continue;
    const walkHook = (node: ts.Node): void => {
      if (ts.isCallExpression(node)) {
        const name = calleeName(node);
        if (name) hooks.push(`${hookKey}:${name}`);
        if (name === "verifyAuth" && node.arguments.length && ts.isArrayLiteralExpression(node.arguments[0])) {
          for (const element of (node.arguments[0] as ts.ArrayLiteralExpression).elements) {
            authModes.add(ts.isPropertyAccessExpression(element) ? element.name.text : element.getText(source));
          }
        }
      } else if (ts.isIdentifier(node) && node.parent === hookNode) {
        hooks.push(`${hookKey}:${node.text}`);
      }
      ts.forEachChild(node, walkHook);
    };
    walkHook(hookNode);
  }

  const serviceCalls = new Set<string>();
  const serviceCallArgs = new Set<string>();
  const localCalls = new Set<string>();
  const handlerNode = propertyNamed(obj, "handler");
  if (handlerNode) {
    const walkHandler = (node: ts.Node): void => {
      const service = serviceCallOf(node);
      if (service) serviceCalls.add(service);
      if (ts.isCallExpression(node)) {
        // The argument keys matter: handing a service `actorId`/`actorOrgId` it did not get
        // before is an authorization change, and the method name alone would not show it.
        const called = serviceCallOf(node.expression);
        if (called) {
          const first = node.arguments[0];
          const keys =
            first && ts.isObjectLiteralExpression(first)
              ? [
                  ...new Set(
                    first.properties
                      .map((prop) => (prop.name ? prop.name.getText(source) : ts.isSpreadAssignment(prop) ? "..." : ""))
                      .filter(Boolean)
                  )
                ].sort()
              : [];
          serviceCallArgs.add(`${called}:${keys.join(",")}`);
        }

        const root = rootIdentifier(node.expression);
        if (root && imports.bindings.has(root)) {
          localCalls.add(
            ts.isPropertyAccessExpression(node.expression) ? `${root}.${node.expression.name.text}` : root
          );
        }
      }
      ts.forEachChild(node, walkHandler);
    };
    walkHandler(handlerNode);
  }

  return {
    line,
    methods,
    url,
    rateLimit,
    authModes: [...authModes].sort(),
    hooks,
    serviceCalls: [...serviceCalls].sort(),
    serviceCallArgs: [...serviceCallArgs].sort(),
    localCalls: [...localCalls].sort(),
    bodyFields: schemaFieldNames(bodyNode),
    paramsFields: schemaFieldNames(paramsNode),
    queryFields: schemaFieldNames(queryNode),
    responseCodes: schemaFieldNames(responseNode),
    bodySchema: schemaDigest(bodyNode, source),
    paramsSchema: schemaDigest(paramsNode, source),
    querySchema: schemaDigest(queryNode, source),
    responseSchema: schemaDigest(responseNode, source),
    registerFn: enclosingRegisterFn(call),
    operationId,
    hidden
  };
};

