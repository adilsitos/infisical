/**
 * Behavioral Signature Builder
 * =============================
 * Emits one hashed behavioral signature per HTTP route so CI can tell whether a change altered
 * what a route *does* rather than how it *looks*.
 *
 * Everything in the hash is derived from a single file's text: the route object
 * (`method`, `url`, `config.rateLimit`, lifecycle hooks, `verifyAuth([...])`), its request and
 * response schemas, the `server.services.<x>.<y>({...})` calls in its handler together with
 * the argument keys they are passed, and its import declarations resolved to module keys. That
 * property is what lets any git revision be signed without a checkout, which is what
 * `pr-behavior-diff.ts` relies on.
 *
 * Schemas are recorded two ways: the top-level field names (so a diff can say which field was
 * added) and a digest of the normalized schema text with `.describe(...)` and comments stripped
 * (so rewording a description is invisible but `.min(1)` -> `.min(8)` is not).
 *
 * SCOPE, stated plainly: a signature covers a route file's own surface. A change *inside* a
 * service - say `secretServiceFactory` gaining a DB write - does not alter any route file's
 * text and so does not move a hash. This is narrower than "behavioral signature" suggests.
 *
 * The Graphify graph (graphify-out/graph.json) is optional enrichment only. Its Leiden
 * community ids are reassigned and its community names are LLM-generated on every run, so
 * nothing graph-derived may enter the hash without churning it for free.
 *
 * Usage:
 *     npm run behavior:discover     # write .behavior-config.json
 *     npm run behavior:build        # write .behavior-manifest.json
 *     npm run behavior:diff -- --ci # committed manifest vs working tree
 *
 * See ./pr-behavior-diff.ts for diffing a pull request or any two git revisions.
 */

