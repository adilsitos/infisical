const matchesGlob = (candidate: string, pattern: string): boolean => {
  if (pattern.endsWith("/**")) return candidate.startsWith(pattern.slice(0, -2));
  if (pattern.startsWith("*")) return candidate.endsWith(pattern.slice(1));
  if (pattern.endsWith("*")) return candidate.startsWith(pattern.slice(0, -1));
  return candidate === pattern || path.posix.basename(candidate) === pattern;
};

export const isExcludedPath = (sourceFile: string, config: BehaviorConfig): boolean =>
  config.excluded_path_globs.some((pattern) => matchesGlob(sourceFile, pattern));

// Path-derived and therefore stable across graphify runs, unlike Leiden community ids.
// Depth 3 under ee/ and server/ (which nest a category under the area), depth 2 elsewhere.
const moduleKeyOfPath = (p: string): string => {
  const stripped = p.replace(/^src\//, "");
  if (!stripped || stripped === ".") return "root";
  const segments = stripped.split("/").filter(Boolean);
  const depth = segments[0] === "ee" || segments[0] === "server" ? 3 : 2;
  return segments.slice(0, depth).join("/");
};

const moduleOfFile = (sourceFile: string): string => moduleKeyOfPath(path.posix.dirname(sourceFile));

interface ResolvedSpecifier {
  moduleKey: string;
  // Backend-relative path when the specifier points inside the backend, else null.
  sourcePath: string | null;
}

// No filesystem probing: the specifier path is used as-is, so a barrel ("@app/lib/errors") and
// a file ("@app/server/config/rateLimiter") both yield a stable key. Both sides of a diff run
// this same function, so comparability holds even where the key is more granular than the
// directory a symbol really lives in.
const resolveSpecifier = (specifier: string, fromFile: string): ResolvedSpecifier => {
  if (specifier.startsWith("node:")) {
    return { moduleKey: `node:${specifier.slice(5).split("/")[0]}`, sourcePath: null };
  }
  if (specifier.startsWith("@app/")) {
    const sourcePath = `src/${specifier.slice("@app/".length)}`;
    return { moduleKey: moduleKeyOfPath(sourcePath), sourcePath };
  }
  if (specifier.startsWith("@bdd_routes/")) {
    const sourcePath = `src/server/routes/bdd/${specifier.slice("@bdd_routes/".length)}`;
    return { moduleKey: moduleKeyOfPath(sourcePath), sourcePath };
  }
  if (specifier.startsWith(".")) {
    const joined = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), specifier));
    return { moduleKey: moduleKeyOfPath(joined), sourcePath: joined };
  }
  const segments = specifier.split("/");
  const name = specifier.startsWith("@") ? segments.slice(0, 2).join("/") : segments[0];
  return { moduleKey: `pkg:${name}`, sourcePath: null };
};

