const commandDiscover = (graphPath: string, configPath: string): void => {
  const graph = loadGraph(graphPath);
  const output: Record<string, unknown> = { _notes: CONFIG_NOTES };

  if (graph) {
    const known = new Set([
      ...DEFAULT_CONFIG_VALUE.graph_relations_behavioral,
      ...DEFAULT_CONFIG_VALUE.graph_relations_ignored
    ]);
    const unclassified = Object.entries(graph.relations)
      .filter(([relation]) => !known.has(relation))
      .map(([relation, count]) => `${relation} (${count})`);

    output._graph = {
      path: path.relative(BACKEND_ROOT, graphPath),
      built_at_commit: graph.commit,
      nodes: graph.nodes,
      edges: graph.edges,
      file_nodes: graph.fileNodes,
      communities: graph.communities,
      relations: graph.relations,
      confidence: graph.confidence,
      unclassified_relations: unclassified
    };
    output._noise_candidates = graph.importDegree.map((entry) => `${entry.label} (${entry.count}) - ${entry.sourceFile}`);

    console.log(
      `Graph: ${graph.nodes} nodes, ${graph.edges} edges, ${graph.fileNodes} file nodes, ${graph.communities} communities`
    );
    if (unclassified.length) console.log(`  Unclassified relations: ${unclassified.join(", ")}`);
  } else {
    console.log(`No graph at ${graphPath} - writing config without graph enrichment (hashes never use it).`);
  }

  const { warn, flush } = collectWarnings();
  const entries = buildFromWorkingTree(DEFAULT_CONFIG_VALUE, warn);
  printWarnings(flush());

  output._routes = {
    total: entries.length,
    files: new Set(entries.map((s) => s.file)).size,
    features: [...new Set(entries.map((s) => s.feature))].sort()
  };
  Object.assign(output, DEFAULT_CONFIG_VALUE);

  writeFileSync(configPath, `${JSON.stringify(output, null, 2)}\n`);
  console.log(`Routes: ${entries.length} across ${new Set(entries.map((s) => s.file)).size} files`);
  console.log(`\nConfig written to ${path.relative(BACKEND_ROOT, configPath)} - review and commit it.`);
};

const commandBuild = (graphPath: string, configPath: string, outputPath: string): void => {
  const config = loadConfig(configPath);
  const { warn, flush } = collectWarnings();
  const entries = buildFromWorkingTree(config, warn);
  const graph = loadGraph(graphPath);
  enrich(entries, graph);

  let revision = "working-tree";
  try {
    revision = `working-tree@${execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      cwd: REPO_ROOT,
      encoding: "utf-8"
    }).trim()}`;
  } catch {
    /* not a git checkout */
  }

  const manifest = assemble(
    entries,
    { revision, scope: "backend/src", route_count: 0, file_count: 0, graph_commit: graph?.commit },
    warn
  );
  printWarnings(flush());

  writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(
    `\nManifest written to ${path.relative(BACKEND_ROOT, outputPath)}\n` +
      `  Routes:   ${manifest._meta.route_count}\n` +
      `  Files:    ${manifest._meta.file_count}\n` +
      `  Features: ${new Set(Object.values(manifest.routes).map((s) => s.feature)).size}\n` +
      `  Graph:    ${graph ? `${graph.commit.slice(0, 12)} (metadata only)` : "absent (not required)"}`
  );
};

const commandDiff = (
  configPath: string,
  baselinePath: string,
  reportPath: string | undefined,
  ci: boolean
): void => {
  if (!existsSync(baselinePath)) {
    fail(
      `No baseline manifest at '${path.relative(BACKEND_ROOT, baselinePath)}'.\n` +
        `Run \`npm run behavior:build\` on the base revision and commit the result first.`
    );
  }
  const config = loadConfig(configPath);
  const { warn, flush } = collectWarnings();
  const baseline = JSON.parse(readFileSync(baselinePath, "utf-8")) as Manifest;
  const current = assemble(
    buildFromWorkingTree(config, warn),
    { revision: "working-tree", scope: "backend/src", route_count: 0, file_count: 0 },
    warn
  );
  printWarnings(flush());

  const report = diffManifests(baseline, current, "backend/src (whole tree)");
  report.meta = {
    base: baseline._meta?.revision ?? "committed-manifest",
    head: "working-tree",
    changed_files: workingTreeChangedFiles(),
    generated_at: new Date().toISOString()
  };
  finishDiff(report, reportPath, ci);
};

const USAGE = `Usage: tsx ./scripts/graphs/signature-builder.ts <command> [options]

Commands:
  discover    Inspect the tree (and graph, if present) and write .behavior-config.json
  build       Write .behavior-manifest.json for the working tree
  diff        Compare the working tree against a committed manifest

Options:
  --graph PATH       graph.json for unhashed enrichment (default: ../graphify-out/graph.json)
  --config PATH      behavior config (default: backend/.behavior-config.json)
  --output PATH      manifest to write (build) (default: backend/.behavior-manifest.json)
  --baseline PATH    manifest to compare against (diff) (default: --output)
  --report PATH      also write the diff report as JSON
  --ci               exit 1 when behavior changed
  -h, --help         show this message

To diff a pull request or two git revisions, see ./pr-behavior-diff.ts
`;

const main = (): void => {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      graph: { type: "string" },
      config: { type: "string" },
      output: { type: "string" },
      baseline: { type: "string" },
      report: { type: "string" },
      ci: { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false }
    }
  });

  const command = positionals[0];
  if (values.help || !command) {
    console.log(USAGE);
    process.exit(values.help ? 0 : 2);
  }

  const graphPath = path.resolve(values.graph ?? DEFAULT_GRAPH);
  const configPath = path.resolve(values.config ?? DEFAULT_CONFIG);
  const outputPath = path.resolve(values.output ?? DEFAULT_MANIFEST);

  switch (command) {
    case "discover":
      commandDiscover(graphPath, configPath);
      return;
    case "build":
      commandBuild(graphPath, configPath, outputPath);
      return;
    case "diff":
      commandDiff(configPath, path.resolve(values.baseline ?? outputPath), values.report, values.ci ?? false);
      return;
    default:
      fail(`Unknown command '${command}'.\n${USAGE}`);
  }
};

if (require.main === module) main();
