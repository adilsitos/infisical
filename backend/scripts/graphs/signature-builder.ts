export interface ChangeDetail {
  field: string;
  added: string[];
  removed: string[];
}

// Provenance for ./project-analyzer.ts, which is a pure join over this report and never shells
// out to git. changed_files carries EVERY backend/src file in the diff, not just route files:
// the whole point of the analyzer is to reach the routes a service-only change touches, which by
// construction move no hash and so appear nowhere else in this report.
export interface DiffReportMeta {
  base: string;
  head: string;
  pr?: { slug: string; number: number };
  changed_files: string[];
  // Head-side changed line ranges per file. Consumed by ./method-index.ts to resolve a change to
  // the methods it lands in; absent on reports written before that existed.
  changed_hunks?: Record<string, { start: number; end: number }[]>;
  generated_at: string;
}

export interface DiffReport {
  scope: string;
  meta?: DiffReportMeta;
  added: { route: string; signature: BehavioralSignature }[];
  removed: { route: string; signature: BehavioralSignature }[];
  changed: { route: string; before: BehavioralSignature; after: BehavioralSignature; details: ChangeDetail[] }[];
  unchanged: number;
}

const SCALAR_FIELDS: (keyof BehavioralSignature)[] = [
  "method",
  "url",
  "feature",
  "rate_limit",
  "body_schema",
  "params_schema",
  "query_schema",
  "response_schema"
];
const LIST_FIELDS: (keyof BehavioralSignature)[] = [
  "auth_modes",
  "hooks",
  "service_calls",
  "service_call_args",
  "local_calls",
  "body_fields",
  "params_fields",
  "query_fields",
  "response_codes",
  "file_imports"
];

const explainChange = (before: BehavioralSignature, after: BehavioralSignature): ChangeDetail[] => {
  const changes: ChangeDetail[] = [];

  for (const field of SCALAR_FIELDS) {
    const from = String(before[field] ?? "");
    const to = String(after[field] ?? "");
    if (from !== to) changes.push({ field, added: to ? [to] : [], removed: from ? [from] : [] });
  }

  for (const field of LIST_FIELDS) {
    const fromSet = new Set((before[field] as string[] | undefined) ?? []);
    const toSet = new Set((after[field] as string[] | undefined) ?? []);
    const added = [...toSet].filter((value) => !fromSet.has(value)).sort();
    const removed = [...fromSet].filter((value) => !toSet.has(value)).sort();
    if (added.length || removed.length) changes.push({ field, added, removed });
  }

  const key = (dep: CrossModuleDep) => `${dep.to}:${dep.node}`;
  const fromCross = new Set((before.cross_module_deps ?? []).map(key));
  const toCross = new Set((after.cross_module_deps ?? []).map(key));
  const addedCross = [...toCross].filter((value) => !fromCross.has(value)).sort();
  const removedCross = [...fromCross].filter((value) => !toCross.has(value)).sort();
  if (addedCross.length || removedCross.length) {
    changes.push({ field: "cross_module_deps", added: addedCross, removed: removedCross });
  }

  // hooks are order-sensitive by design, so a pure reorder shows no set difference.
  if (!changes.length && JSON.stringify(before.hooks) !== JSON.stringify(after.hooks)) {
    changes.push({ field: "hooks (reordered)", added: after.hooks, removed: before.hooks });
  }

  return changes;
};

export const diffManifests = (baseline: Manifest, current: Manifest, scope: string): DiffReport => {
  const report: DiffReport = { scope, added: [], removed: [], changed: [], unchanged: 0 };
  const before = baseline.routes ?? {};
  const after = current.routes ?? {};

  for (const [route, signature] of Object.entries(after)) {
    const previous = before[route];
    if (!previous) report.added.push({ route, signature });
    else if (previous.hash !== signature.hash) {
      report.changed.push({ route, before: previous, after: signature, details: explainChange(previous, signature) });
    } else report.unchanged += 1;
  }

  for (const [route, signature] of Object.entries(before)) {
    if (!(route in after)) report.removed.push({ route, signature });
  }

  report.added.sort((a, b) => a.route.localeCompare(b.route));
  report.removed.sort((a, b) => a.route.localeCompare(b.route));
  report.changed.sort((a, b) => a.route.localeCompare(b.route));
  return report;
};

export const formatReport = (report: DiffReport): string => {
  const lines: string[] = ["", "  Behavior Change Report", ""];

  for (const item of report.changed) {
    lines.push(`  CHANGED: ${item.route}  (feature: ${item.after.feature})`);
    lines.push(`     hash: ${item.before.hash} -> ${item.after.hash}`);
    for (const change of item.details) {
      for (const value of change.added) lines.push(`     + ${change.field}: ${value}`);
      for (const value of change.removed) lines.push(`     - ${change.field}: ${value}`);
    }
    lines.push("");
  }

  for (const item of report.added) {
    lines.push(`  NEW: ${item.route}  (feature: ${item.signature.feature})`);
    if (item.signature.service_calls.length) {
      lines.push(`     services: ${item.signature.service_calls.slice(0, 5).join(", ")}`);
    }
    if (item.signature.auth_modes.length) lines.push(`     auth: ${item.signature.auth_modes.join(", ")}`);
    const modules = [...new Set(item.signature.cross_module_deps.map((dep) => dep.to))].sort();
    if (modules.length) lines.push(`     touches: ${modules.slice(0, 6).join(", ")}`);
    lines.push("");
  }

  for (const item of report.removed) lines.push(`  REMOVED: ${item.route}`);
  if (report.removed.length) lines.push("");

  const total = report.unchanged + report.changed.length + report.added.length + report.removed.length;
  lines.push(
    `  Summary: ${report.changed.length} changed, ${report.added.length} new, ` +
      `${report.removed.length} removed, ${report.unchanged} unchanged out of ${total} routes`
  );
  lines.push(`  Scope: ${report.scope}`);

  return lines.join("\n");
};

// Tracked edits plus untracked additions, so `behavior:diff` against the working tree can hand
// ./project-analyzer.ts the same changed_files list a pull request diff would.
export const workingTreeChangedFiles = (): string[] => {
  const run = (args: string[]): string[] => {
    try {
      return execFileSync("git", args, { cwd: REPO_ROOT, encoding: "utf-8", maxBuffer: 64 * 1024 * 1024 })
        .split("\n")
        .map((line) => line.trim())
        .filter(Boolean);
    } catch {
      return [];
    }
  };

  const scope = `${BACKEND_PREFIX}src`;
  const files = [
    ...run(["diff", "--name-only", "HEAD", "--", scope]),
    ...run(["ls-files", "--others", "--exclude-standard", "--", scope])
  ];
  return [...new Set(files.map((file) => file.slice(BACKEND_PREFIX.length)))].sort();
};

export const collectWarnings = () => {
  const warnings: string[] = [];
  return { warn: (message: string) => warnings.push(message), flush: () => warnings };
};

export const printWarnings = (warnings: string[]): void => {
  const seen = new Set<string>();
  for (const message of warnings) {
    if (seen.has(message)) continue;
    seen.add(message);
    console.warn(`  warn: ${message}`);
  }
};

export const finishDiff = (report: DiffReport, reportPath: string | undefined, ci: boolean): void => {
  console.log(formatReport(report));
  if (reportPath) writeFileSync(path.resolve(reportPath), `${JSON.stringify(report, null, 2)}\n`);
  if (ci && (report.changed.length || report.added.length || report.removed.length)) process.exit(1);
};

