export interface BehavioralSignature {
  method: string;
  url: string;
  feature: string;
  file: string;
  location: string;
  register_fn: string;
  operation_id: string;
  hidden: boolean;
  rate_limit: string;
  auth_modes: string[];
  hooks: string[];
  service_calls: string[];
  service_call_args: string[];
  local_calls: string[];
  body_fields: string[];
  params_fields: string[];
  query_fields: string[];
  response_codes: string[];
  body_schema: string;
  params_schema: string;
  query_schema: string;
  response_schema: string;
  file_imports: string[];
  cross_module_deps: CrossModuleDep[];
  graph?: GraphMeta;
  hash: string;
}

// Hashed as an array of pairs so key order is fixed by construction, with no post-hoc string
// surgery. `hooks` keeps source order so reordering middleware registers as a change;
// everything else is deduped and sorted upstream. location, register_fn, operation_id and the
// graph block are metadata and deliberately absent.
const computeHash = (signature: BehavioralSignature): string => {
  const payload: [string, unknown][] = [
    ["method", signature.method],
    ["url", signature.url],
    ["feature", signature.feature],
    ["rate_limit", signature.rate_limit],
    ["auth_modes", signature.auth_modes],
    ["hooks", signature.hooks],
    ["service_calls", signature.service_calls],
    ["service_call_args", signature.service_call_args],
    ["local_calls", signature.local_calls],
    ["body_fields", signature.body_fields],
    ["params_fields", signature.params_fields],
    ["query_fields", signature.query_fields],
    ["response_codes", signature.response_codes],
    ["body_schema", signature.body_schema],
    ["params_schema", signature.params_schema],
    ["query_schema", signature.query_schema],
    ["response_schema", signature.response_schema],
    ["file_imports", signature.file_imports],
    ["cross_module_deps", signature.cross_module_deps.map((dep) => `${dep.to}:${dep.node}`).sort()]
  ];
  return createHash("sha256").update(JSON.stringify(payload)).digest("hex").slice(0, 12);
};

export const signaturesForFile = (
  relPath: string,
  text: string,
  config: BehaviorConfig,
  warn: (message: string) => void
): BehavioralSignature[] => {
  if (!text.includes(".route({")) return [];

  const source = ts.createSourceFile(relPath, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const imports = readImports(source, relPath, config);
  const feature = moduleOfFile(relPath);
  const signatures: BehavioralSignature[] = [];

  const visit = (node: ts.Node): void => {
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      node.expression.name.text === "route" &&
      node.arguments.length === 1 &&
      ts.isObjectLiteralExpression(node.arguments[0])
    ) {
      const site = readRouteObject(
        node.arguments[0] as ts.ObjectLiteralExpression,
        node,
        source,
        relPath,
        imports,
        config,
        warn
      );
      if (site) {
        for (const method of site.methods) {
          const signature: BehavioralSignature = {
            method,
            url: site.url ?? DYNAMIC_URL,
            feature,
            file: relPath,
            location: `L${site.line}`,
            register_fn: site.registerFn,
            operation_id: site.operationId,
            hidden: site.hidden,
            rate_limit: site.rateLimit,
            auth_modes: site.authModes,
            hooks: site.hooks,
            service_calls: site.serviceCalls,
            service_call_args: site.serviceCallArgs,
            local_calls: site.localCalls,
            body_fields: site.bodyFields,
            params_fields: site.paramsFields,
            query_fields: site.queryFields,
            response_codes: site.responseCodes,
            body_schema: site.bodySchema,
            params_schema: site.paramsSchema,
            query_schema: site.querySchema,
            response_schema: site.responseSchema,
            file_imports: imports.fileImports,
            cross_module_deps: imports.crossModuleDeps,
            hash: ""
          };
          signature.hash = computeHash(signature);
          signatures.push(signature);
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);

  return signatures;
};

